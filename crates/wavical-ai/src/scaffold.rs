#![forbid(unsafe_code)]

//! AI-assisted project scaffolding generator, validator, and capability scanner (Phase 3 WP8).
//!
//! # Security Guarantees:
//! - **Untrusted Model Output**: Model output is treated as untrusted data.
//! - **Fixed Extension Allowlist**: Only `.html`, `.css`, `.js`, `.json`, `.svg`, and `.txt` files.
//! - **Strict Path Sanitization**: Rejects path traversal (`..`), absolute paths, drive letters,
//!   UNC paths, alternate data streams (`:`), Windows reserved device names (`CON`, `PRN`, `NUL`, etc.),
//!   and null bytes.
//! - **Project Confinement**: Files are strictly written inside `<project_dir>/src/`.
//! - **Forbidden Configuration Files**: The model cannot generate `wavical.config.js` or files
//!   outside `src/`.
//! - **Hard Limits**:
//!   - Maximum 20 files (`MAX_AI_INIT_FILES`).
//!   - Maximum 1 MB total aggregate content size (`MAX_AI_INIT_TOTAL_BYTES`).
//! - **Capability Sovereignty**: The model NEVER decides capabilities. The CLI scans code for
//!   `wavical.invoke(` calls, presents candidates to the developer, and generates `wavical.config.js`
//!   purely from developer selection (default: none).

