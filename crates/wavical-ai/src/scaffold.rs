    #[test]
    fn test_total_size_boundary() {
        // 1 MB exactly passes
        let ok_file = vec![GeneratedFile {
            path: "big.txt".to_string(),
            content: "a".repeat(1024 * 1024),
        }];
        assert!(validate_scaffold_files(&ok_file).is_ok());

        // 1 MB + 1 byte fails
        let over_file = vec![GeneratedFile {
            path: "big.txt".to_string(),
            content: "a".repeat(1024 * 1024 + 1),
        }];
        assert!(matches!(
            validate_scaffold_files(&over_file),
            Err(ScaffoldError::TotalSizeExceeded { .. })
        ));

        // 2 MB fails
        let two_mb = vec![GeneratedFile {
            path: "huge.txt".to_string(),
            content: "a".repeat(2 * 1024 * 1024),
        }];
        assert!(matches!(
            validate_scaffold_files(&two_mb),
            Err(ScaffoldError::TotalSizeExceeded { .. })
        ));

        // Multibyte boundary
        let euro = "€"; // 3 bytes
        let repeat_count = (1024 * 1024) / 3;
        let mut multibyte_content = euro.repeat(repeat_count);
        multibyte_content.push_str("ab"); // total bytes = 1,048,577 (over limit)
        let multibyte_over = vec![GeneratedFile {
            path: "multibyte.txt".to_string(),
            content: multibyte_content,
        }];
        assert!(matches!(
            validate_scaffold_files(&multibyte_over),
            Err(ScaffoldError::TotalSizeExceeded { .. })
        ));
    }

    #[test]
    fn test_capability_scanning() {
        let files = vec![
            GeneratedFile {
                path: "index.html".to_string(),
                content: r#"<button onclick="wavical.invoke('clipboard.read')">Paste</button>"#
                    .to_string(),
            },
            GeneratedFile {
                path: "app.js".to_string(),
                content: r#"
                    const x = await wavical.invoke("notify.send", { title: "Hi" });
                    const y = await wavical.invoke("dialog.openFile");
                    const fake = await wavical.invoke("nonexistent.method");
                "#
                .to_string(),
            },
            GeneratedFile {
                path: "data.txt".to_string(),
                content: "wavical.invoke('fs.readGranted')".to_string(), // not scanned because .txt
            },
        ];

        let caps = scan_used_capabilities(&files);
        assert!(caps.contains("clipboard.read"));
        assert!(caps.contains("notify.send"));
        assert!(caps.contains("dialog.openFile"));
        assert!(!caps.contains("nonexistent.method"));
        assert!(!caps.contains("fs.readGranted"));
    }

    #[test]
    fn test_capability_grant_in_model_output_ignored() {
        // Model attempts to include capability grants in its JSON
        let json_with_claims = r#"[
            {"path": "index.html", "content": "<h1>Hello</h1>"},
            {"path": "app.js", "content": "console.log(1);"}
        ]"#;

        let parsed = parse_scaffold_response(json_with_claims).unwrap();
        // Model provides no valid invoke calls
        let scanned = scan_used_capabilities(&parsed);
        assert!(scanned.is_empty(), "No capabilities should be auto-granted");

        // CLI generates wavical.config.js with zero capabilities by default
        let config = generate_scaffold_config_js("my-test-app", "My Test App", &[]);
        assert!(config.contains("capabilities: {}"));
        assert!(!config.contains("'clipboard.read': true"));
    }

