/// Execute AI chat completions to generate scaffold code using the configured backend mode.
#[allow(clippy::too_many_arguments)]
pub fn execute_scaffold_with_mode(
    mode: ChatExecutionMode,
    app_data_path: &Path,
    app_id: &str,
    description: &str,
    local_client: &reqwest::blocking::Client,
    local_channel: Option<&EngineChannel>,
    local_model_id: Option<&str>,
    cloud_client: &reqwest::blocking::Client,
    cloud_config: Option<&CloudChatConfig>,
    consent_provider: &dyn ConsentDialogProvider,
) -> Result<String, ScaffoldError> {
    let messages = vec![
        ChatMessage {
            role: ChatRole::System,
            content: build_scaffold_system_prompt(),
        },
        ChatMessage {
            role: ChatRole::User,
            content: build_scaffold_user_prompt(app_id, description),
        },
    ];

    let request = ChatRequest {
        messages,
        max_tokens: Some(4096),
        temperature: Some(0.2),
        stream: Some(true),
    };

    let stream_config = StreamChatConfig {
        config_max_tokens: 4096,
        wall_clock_timeout: Duration::from_secs(120),
        max_streamed_chars: 100_000,
    };

    let cancel_flag = Arc::new(AtomicBool::new(false));
    let accumulated = Arc::new(Mutex::new(String::new()));
    let accumulated_clone = accumulated.clone();
    let status_res = Arc::new(Mutex::new(None));
    let status_clone = status_res.clone();

    execute_chat_with_mode(
        mode,
        app_data_path,
        app_id,
        "cli-scaffold",
        1,
        &request,
        &stream_config,
        &cancel_flag,
        local_client,
        local_channel,
        local_model_id,
        cloud_client,
        cloud_config,
        consent_provider,
        move |chunk| {
            accumulated_clone.lock().unwrap().push_str(chunk);
        },
        move |status, err, _backend| {
            *status_clone.lock().unwrap() = Some((status, err));
        },
    );

    let (status, err) = status_res.lock().unwrap().take().unwrap_or((
        ChatStreamStatus::Failed,
        Some("no response received from AI backend".to_string()),
    ));

    match status {
        ChatStreamStatus::Done => {
            let content = accumulated.lock().unwrap().clone();
            Ok(content)
        }
        ChatStreamStatus::Cancelled => Err(ScaffoldError::BackendError(
            "AI scaffolding generation cancelled".to_string(),
        )),
        ChatStreamStatus::Truncated => {
            let content = accumulated.lock().unwrap().clone();
            Ok(content)
        }
        ChatStreamStatus::Failed => {
            Err(ScaffoldError::BackendError(err.unwrap_or_else(|| {
                "AI scaffolding generation failed".to_string()
            })))
        }
    }
}

/// High-level function to generate application scaffold files using the specified AI backend mode.
pub fn generate_scaffold_code(
    mode: ChatExecutionMode,
    app_data_path: &Path,
    app_id: &str,
    description: &str,
    cloud_config: Option<&CloudChatConfig>,
    consent_provider: Option<&dyn ConsentDialogProvider>,
) -> Result<String, ScaffoldError> {
    let local_client = reqwest::blocking::Client::builder()
        .timeout(Duration::from_secs(120))
        .build()
        .map_err(|e| {
            ScaffoldError::BackendError(format!("failed to initialize local client: {e}"))
        })?;

    let cloud_client = crate::cloud_client::create_cloud_http_client(None).map_err(|e| {
        ScaffoldError::BackendError(format!("failed to initialize cloud client: {e}"))
    })?;

    let default_consent = crate::consent::NativeConsentDialogProvider;
    let provider: &dyn ConsentDialogProvider = consent_provider.unwrap_or(&default_consent);

    execute_scaffold_with_mode(
        mode,
        app_data_path,
        app_id,
        description,
        &local_client,
        None,
        None,
        &cloud_client,
        cloud_config,
        provider,
    )
}

