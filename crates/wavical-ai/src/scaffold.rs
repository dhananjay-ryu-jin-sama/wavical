/// Errors encountered during AI project scaffolding.
#[derive(Debug, Error, PartialEq, Eq)]
pub enum ScaffoldError {
    #[error("file count limit exceeded: {count} files exceeds maximum of {max}")]
    TooManyFiles { count: usize, max: usize },

    #[error("total generated size exceeded: {size} bytes exceeds maximum of {max} bytes (1 MB)")]
    TotalSizeExceeded { size: usize, max: usize },

    #[error(
        "disallowed file extension for '{path}': only .html, .css, .js, .json, .svg, and .txt files are permitted"
    )]
    DisallowedExtension { path: String },

    #[error("missing file extension for '{path}'")]
    MissingExtension { path: String },

    #[error("invalid path '{path}': {reason}")]
    InvalidPath { path: String, reason: String },

    #[error(
        "model attempted to generate '{path}': generating configuration files or files outside src/ is forbidden"
    )]
    ConfigFileForbidden { path: String },

    #[error("failed to parse AI generation output: {0}")]
    ParseError(String),

    #[error("AI backend error: {0}")]
    BackendError(String),

    #[error("I/O error during project scaffolding: {0}")]
    IoError(String),
}

/// A single file generated by the AI model.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GeneratedFile {
    /// Relative path inside `src/` (e.g. "index.html", "styles.css", "components/nav.html").
    pub path: String,
    /// UTF-8 file content.
    pub content: String,
}

/// Standard Windows reserved device names (case-insensitive).
const RESERVED_DEVICE_NAMES: &[&str] = &[
    "CON", "PRN", "AUX", "NUL", "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8",
    "COM9", "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9", "CONIN$",
    "CONOUT$",
];

/// Check if a path component matches any Windows reserved device name.
fn is_reserved_device_name(name: &str) -> bool {
    let stem = name.split('.').next().unwrap_or(name);
    let upper = stem.trim().to_ascii_uppercase();
    RESERVED_DEVICE_NAMES.contains(&upper.as_str())
}

/// Check if a file extension is in the allowed whitelist (`.html`, `.css`, `.js`, `.json`, `.svg`, `.txt`).
fn is_allowed_extension(ext: &str) -> bool {
    let lower = ext.trim().to_ascii_lowercase();
    AI_INIT_ALLOWED_EXTENSIONS.contains(&lower.as_str())
}

/// Sanitize and validate a relative file path proposed by the AI model.
///
/// Ensures the path:
/// 1. Is not empty and contains no null bytes.
/// 2. Does not attempt to write `wavical.config.js` or root files.
/// 3. Does not use absolute paths, drive letters, or UNC shares.
/// 4. Does not use alternate data streams (`:`).
/// 5. Does not contain path traversal (`..`).
/// 6. Does not use Windows reserved device names (`CON`, `PRN`, etc.).
/// 7. Uses only allowed extensions (`.html`, `.css`, `.js`, `.json`, `.svg`, `.txt`).
pub fn sanitize_and_validate_scaffold_path(raw_path: &str) -> Result<String, ScaffoldError> {
    let trimmed = raw_path.trim();
    if trimmed.is_empty() {
        return Err(ScaffoldError::InvalidPath {
            path: raw_path.to_string(),
            reason: "path cannot be empty".to_string(),
        });
    }

    if trimmed.contains('\0') {
        return Err(ScaffoldError::InvalidPath {
            path: raw_path.to_string(),
            reason: "null bytes are forbidden".to_string(),
        });
    }

    let normalized = trimmed.replace('\\', "/");

    // Check for drive letters (e.g. C:) or alternate data streams (a:b)
    if normalized.contains(':') {
        return Err(ScaffoldError::InvalidPath {
            path: raw_path.to_string(),
            reason: "drive letters and alternate data streams (':') are forbidden".to_string(),
        });
    }

    // Check for absolute paths or UNC paths
    if normalized.starts_with('/') {
        return Err(ScaffoldError::InvalidPath {
            path: raw_path.to_string(),
            reason: "absolute paths are forbidden".to_string(),
        });
    }

    // Check for attempts to overwrite configuration files or files outside src/
    let lower = normalized.to_ascii_lowercase();
    if lower == "wavical.config.js"
        || lower == "wavical.config.mjs"
        || lower == "wavical.config.ts"
        || lower.ends_with("/wavical.config.js")
        || lower == ".gitignore"
        || lower.starts_with(".env")
        || lower == "package.json"
    {
        return Err(ScaffoldError::ConfigFileForbidden {
            path: raw_path.to_string(),
        });
    }

    // Strip leading "./" and "src/" if provided by the model
    let mut stripped = normalized.as_str();
    while let Some(s) = stripped.strip_prefix("./") {
        stripped = s;
    }
    if let Some(s) = stripped.strip_prefix("src/") {
        stripped = s;
    }

    if stripped.is_empty() {
        return Err(ScaffoldError::InvalidPath {
            path: raw_path.to_string(),
            reason: "path cannot be empty".to_string(),
        });
    }

    // Again check if stripped matches wavical.config.js
    if stripped.eq_ignore_ascii_case("wavical.config.js") {
        return Err(ScaffoldError::ConfigFileForbidden {
            path: raw_path.to_string(),
        });
    }

    // Validate path segments
    let segments: Vec<&str> = stripped.split('/').collect();
    for seg in &segments {
        let seg_trimmed = seg.trim();
        if seg_trimmed.is_empty() {
            return Err(ScaffoldError::InvalidPath {
                path: raw_path.to_string(),
                reason: "empty path segments are forbidden".to_string(),
            });
        }
        if *seg == "." || *seg == ".." {
            return Err(ScaffoldError::InvalidPath {
                path: raw_path.to_string(),
                reason: "path traversal ('..') is forbidden".to_string(),
            });
        }
        if is_reserved_device_name(seg_trimmed) {
            return Err(ScaffoldError::InvalidPath {
                path: raw_path.to_string(),
                reason: format!("'{seg_trimmed}' is a reserved Windows device name"),
            });
        }
    }

    // Validate file extension on the final component
    let filename = segments.last().unwrap();
    let ext = filename.split('.').next_back().unwrap_or("");
    if ext == *filename || ext.is_empty() {
        return Err(ScaffoldError::MissingExtension {
            path: raw_path.to_string(),
        });
    }

    if !is_allowed_extension(ext) {
        return Err(ScaffoldError::DisallowedExtension {
            path: raw_path.to_string(),
        });
    }

    Ok(stripped.to_string())
}

/// Validate a collection of generated files against count, size, and path constraints.
pub fn validate_scaffold_files(
    files: &[GeneratedFile],
) -> Result<Vec<GeneratedFile>, ScaffoldError> {
    if files.is_empty() {
        return Err(ScaffoldError::ParseError(
            "model output contained zero files".to_string(),
        ));
    }

    if files.len() > MAX_AI_INIT_FILES {
        return Err(ScaffoldError::TooManyFiles {
            count: files.len(),
            max: MAX_AI_INIT_FILES,
        });
    }

    let mut total_bytes: usize = 0;
    let mut validated = Vec::with_capacity(files.len());

    for file in files {
        let content_len = file.content.len();
        total_bytes =
            total_bytes
                .checked_add(content_len)
                .ok_or(ScaffoldError::TotalSizeExceeded {
                    size: usize::MAX,
                    max: MAX_AI_INIT_TOTAL_BYTES,
                })?;

        if total_bytes > MAX_AI_INIT_TOTAL_BYTES {
            return Err(ScaffoldError::TotalSizeExceeded {
                size: total_bytes,
                max: MAX_AI_INIT_TOTAL_BYTES,
            });
        }

        let clean_path = sanitize_and_validate_scaffold_path(&file.path)?;
        validated.push(GeneratedFile {
            path: clean_path,
            content: file.content.clone(),
        });
    }

    Ok(validated)
}

/// Parse model output into structured files.
///
/// Supports:
/// 1. Direct JSON array: `[{"path": "...", "content": "..."}]`
/// 2. Markdown fenced JSON block: ````json [...] ````
/// 3. Markdown fenced code blocks with file path headers.
///
/// Any capability declarations in the raw output are strictly ignored.
pub fn parse_scaffold_response(raw_text: &str) -> Result<Vec<GeneratedFile>, ScaffoldError> {
    let trimmed = raw_text.trim();
    if trimmed.is_empty() {
        return Err(ScaffoldError::ParseError(
            "model returned empty output".to_string(),
        ));
    }

    // 1. Try parsing directly as JSON array
    if trimmed.starts_with('[')
        && let Ok(files) = serde_json::from_str::<Vec<GeneratedFile>>(trimmed)
    {
        return validate_scaffold_files(&files);
    }

    // 2. Try extracting from markdown code fence containing JSON
    if let Some(json_str) = extract_fenced_json(trimmed)
        && let Ok(files) = serde_json::from_str::<Vec<GeneratedFile>>(&json_str)
    {
        return validate_scaffold_files(&files);
    }

    // 3. Try parsing individual fenced code blocks with file paths (e.g. ```html index.html ...)
    let files = extract_fenced_file_blocks(trimmed);
    if !files.is_empty() {
        return validate_scaffold_files(&files);
    }

    Err(ScaffoldError::ParseError(
        "failed to parse model output as valid JSON array of files".to_string(),
    ))
}

/// Extract content from ```json ... ``` code fence.
fn extract_fenced_json(text: &str) -> Option<String> {
    let start_tag = "```json";
    let start_idx = text.find(start_tag)?;
    let after_start = &text[start_idx + start_tag.len()..];
    let end_idx = after_start.find("```")?;
    Some(after_start[..end_idx].trim().to_string())
}

/// Extract file blocks from markdown fences with headers like ````html index.html or ````file:index.html.
fn extract_fenced_file_blocks(text: &str) -> Vec<GeneratedFile> {
    let mut files = Vec::new();
    let mut remaining = text;

    while let Some(start) = remaining.find("```") {
        let after_fence = &remaining[start + 3..];
        let newline = match after_fence.find('\n') {
            Some(n) => n,
            None => break,
        };

        let header = after_fence[..newline].trim();
        let content_start = newline + 1;
        let content_and_rest = &after_fence[content_start..];

        let end_fence = match content_and_rest.find("```") {
            Some(e) => e,
            None => break,
        };

        let content = &content_and_rest[..end_fence];
        remaining = &content_and_rest[end_fence + 3..];

        // Parse path from header:
        // Examples: "file:index.html", "path:index.html", "html index.html", "index.html"
        let path_candidate = if let Some(p) = header.strip_prefix("file:") {
            p.trim()
        } else if let Some(p) = header.strip_prefix("path:") {
            p.trim()
        } else {
            let parts: Vec<&str> = header.split_whitespace().collect();
            if parts.len() >= 2 {
                parts[1]
            } else if parts.len() == 1 && parts[0].contains('.') {
                parts[0]
            } else {
                continue;
            }
        };

        if !path_candidate.is_empty() {
            files.push(GeneratedFile {
                path: path_candidate.to_string(),
                content: content.trim_end_matches('\r').to_string(),
            });
        }
    }

    files
}

/// Scan generated source files for `wavical.invoke(` calls to detect capability usage.
///
/// Returns a sorted, deduplicated set of detected capability names matching `KNOWN_CAPABILITIES`.
pub fn scan_used_capabilities(files: &[GeneratedFile]) -> BTreeSet<String> {
    let mut detected = BTreeSet::new();

    for file in files {
        let lower_path = file.path.to_ascii_lowercase();
        // Only inspect JavaScript and HTML files
        if !lower_path.ends_with(".js") && !lower_path.ends_with(".html") {
            continue;
        }

        let content = &file.content;
        let mut idx = 0;
        let invoke_pattern = "wavical.invoke(";

        while let Some(pos) = content[idx..].find(invoke_pattern) {
            let after_invoke = &content[idx + pos + invoke_pattern.len()..];
            let trimmed_arg = after_invoke.trim_start();

            // Extract string literal inside quotes
            let method_name = if let Some(stripped) = trimmed_arg.strip_prefix('"') {
                stripped.split('"').next()
            } else if let Some(stripped) = trimmed_arg.strip_prefix('\'') {
                stripped.split('\'').next()
            } else if let Some(stripped) = trimmed_arg.strip_prefix('`') {
                stripped.split('`').next()
            } else {
                None
            };

            if let Some(name) = method_name {
                let trimmed_name = name.trim();
                if KNOWN_CAPABILITIES.contains(&trimmed_name) {
                    detected.insert(trimmed_name.to_string());
                }
            }

            idx += pos + invoke_pattern.len();
        }
    }

    detected
}

/// Generate `wavical.config.js` with only the user-approved capabilities.
///
/// Note: The model NEVER outputs this file. It is synthesized by the CLI in safe Rust.
pub fn generate_scaffold_config_js(
    app_id: &str,
    title: &str,
    granted_capabilities: &[String],
) -> String {
    let mut cap_lines = Vec::new();
    let mut has_ai_cap = false;

    for cap in granted_capabilities {
        cap_lines.push(format!("    '{cap}': true,"));
        if cap.starts_with("ai.") {
            has_ai_cap = true;
        }
    }

    let caps_body = if cap_lines.is_empty() {
        "  capabilities: {},\n".to_string()
    } else {
        format!("  capabilities: {{\n{}\n  }},\n", cap_lines.join("\n"))
    };

    let ai_section = if has_ai_cap {
        "  ai: {\n    enabled: true,\n    mode: 'local',\n  },\n"
    } else {
        ""
    };

    format!(
        "export default {{\n  appId: '{app_id}',\n  window: {{\n    width: 1200,\n    height: 800,\n    title: '{title}',\n  }},\n{caps_body}{ai_section}}};\n"
    )
}

/// Write scaffolded project files to the target directory.
pub fn write_scaffolded_project(
    target_dir: &Path,
    app_id: &str,
    title: &str,
    files: &[GeneratedFile],
    granted_capabilities: &[String],
) -> Result<Vec<PathBuf>, ScaffoldError> {
    let src_dir = target_dir.join("src");
    std::fs::create_dir_all(&src_dir)
        .map_err(|e| ScaffoldError::IoError(format!("failed to create src directory: {e}")))?;

    let mut written_files = Vec::new();

    // 1. Write generated files inside src/
    for file in files {
        let clean_path = sanitize_and_validate_scaffold_path(&file.path)?;
        let full_path = src_dir.join(&clean_path);

        if let Some(parent) = full_path.parent() {
            std::fs::create_dir_all(parent).map_err(|e| {
                ScaffoldError::IoError(format!(
                    "failed to create subdirectory '{}': {e}",
                    parent.display()
                ))
            })?;
        }

        std::fs::write(&full_path, &file.content).map_err(|e| {
            ScaffoldError::IoError(format!("failed to write '{}': {e}", full_path.display()))
        })?;

        written_files.push(full_path);
    }

    // 2. Write wavical.config.js generated purely by the CLI
    let config_content = generate_scaffold_config_js(app_id, title, granted_capabilities);
    let config_path = target_dir.join("wavical.config.js");
    std::fs::write(&config_path, config_content).map_err(|e| {
        ScaffoldError::IoError(format!(
            "failed to write configuration '{}': {e}",
            config_path.display()
        ))
    })?;
    written_files.push(config_path);

    // 3. Write standard .gitignore
    let gitignore_content = "# Build artifacts\ndist/\ntarget/\n\n# Node\nnode_modules/\n\n# Environment & OS\n.env\n.DS_Store\nThumbs.db\n";
    let gitignore_path = target_dir.join(".gitignore");
    std::fs::write(&gitignore_path, gitignore_content).map_err(|e| {
        ScaffoldError::IoError(format!(
            "failed to write .gitignore '{}': {e}",
            gitignore_path.display()
        ))
    })?;
    written_files.push(gitignore_path);

    Ok(written_files)
}

