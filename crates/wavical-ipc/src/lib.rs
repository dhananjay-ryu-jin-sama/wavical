    /// ZERO INFORMATION LEAKAGE TEST (WP8 Self-Review):
    /// Verify that errors emitted by handlers containing internal filesystem paths or OS symbols
    /// are strictly sanitized to GENERIC_HANDLER_ERROR before reaching the webview.
    #[test]
    fn test_handler_error_sanitization_never_leaks_paths() {
        let mut registry = HandlerRegistry::new();
        registry.register("internal.failing", |_| {
            Err("Failed to open C:\\Users\\Admin\\secret.db: permission denied".to_string())
        });

        let mut caps = Capabilities::new();
        caps.grant("internal.failing");

        let req = Request {
            id: 88,
            method: "internal.failing".to_string(),
            params: serde_json::Value::Null,
        };

        let resp = dispatch(&req, &caps, &registry);
        assert!(!resp.ok);
        assert_eq!(resp.error.as_deref(), Some(GENERIC_HANDLER_ERROR));
        assert!(!resp.error.unwrap().contains("C:\\"));
    }

