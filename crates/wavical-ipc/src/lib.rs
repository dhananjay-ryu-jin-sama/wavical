/// Maximum raw IPC message size in bytes before parsing (1 MB default).
pub const MAX_MESSAGE_SIZE_BYTES: usize = 1024 * 1024;

/// Maximum JSON nesting depth for objects and arrays.
pub const MAX_JSON_DEPTH: usize = 32;

/// Maximum allowable request ID (JavaScript Number.MAX_SAFE_INTEGER = 2^53 - 1).
pub const MAX_REQUEST_ID: u64 = 9_007_199_254_740_991;

/// Minimum allowable method name length.
pub const MIN_METHOD_NAME_LENGTH: usize = 1;

/// Maximum allowable method name length.
pub const MAX_METHOD_NAME_LENGTH: usize = 64;

/// Generic error message returned to untrusted callers for both ungranted and unknown methods.
/// This prevents capability enumeration and timing oracles.
pub const GENERIC_METHOD_ERROR: &str = "Method not allowed or not found";

/// Generic error message returned when an IPC handler execution fails with sensitive paths or details.
pub const GENERIC_HANDLER_ERROR: &str = "Handler execution failed";

/// Framework package version for core.ping.
pub const FRAMEWORK_VERSION: &str = env!("CARGO_PKG_VERSION");

/// Incoming IPC request payload from a webview context.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Request {
    /// Unique integer request identifier generated by the caller.
    pub id: u64,
    /// Requested RPC method name (e.g. "core.ping").
    pub method: String,
    /// Arbitrary JSON parameters passed to the handler (defaults to null if omitted).
    #[serde(default)]
    pub params: serde_json::Value,
}

/// Outgoing IPC response payload sent back to the webview context.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Response {
    /// Matching request identifier.
    pub id: u64,
    /// Whether the method invocation was successful.
    pub ok: bool,
    /// Result payload if successful (omitted on failure).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub result: Option<serde_json::Value>,
    /// Error description if failed (omitted on success).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
}

impl Response {
    /// Construct a successful response payload.
    pub fn success(id: u64, result: serde_json::Value) -> Self {
        Self {
            id,
            ok: true,
            result: Some(result),
            error: None,
        }
    }

    /// Construct a failed response payload.
    pub fn error(id: u64, error: impl Into<String>) -> Self {
        Self {
            id,
            ok: false,
            result: None,
            error: Some(error.into()),
        }
    }
}

/// Enumeration of all IPC rejection reasons in wavical-ipc.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum IpcError {
    #[error("Message exceeds maximum allowed size of {max} bytes (received {size} bytes)")]
    MessageTooLarge { size: usize, max: usize },

    #[error("Message is empty")]
    EmptyMessage,

    #[error("Message contains null byte")]
    NullByteDetected,

    #[error("JSON nesting depth exceeds maximum allowed limit of {max} levels (reached {depth})")]
    RecursionLimitExceeded { depth: usize, max: usize },

    #[error("JSON deserialization failed: {0}")]
    InvalidJson(String),

    #[error("Request ID {id} exceeds maximum safe integer range ({max})")]
    InvalidIdRange { id: u64, max: u64 },

    #[error("Invalid method name: {0}")]
    InvalidMethodName(String),
}

/// Inspect a raw string's nesting depth before full JSON deserialization.
///
/// Scans quotes and escape sequences to accurately track object and array brackets
/// without allocating memory or risking stack overflow.
pub fn check_nesting_depth(raw: &str, max_depth: usize) -> Result<(), IpcError> {
    let mut depth: usize = 0;
    let mut in_string = false;
    let mut is_escaped = false;

    for &b in raw.as_bytes() {
        if in_string {
            if is_escaped {
                is_escaped = false;
            } else if b == b'\\' {
                is_escaped = true;
            } else if b == b'"' {
                in_string = false;
            }
        } else {
            match b {
                b'"' => in_string = true,
                b'{' | b'[' => {
                    depth += 1;
                    if depth > max_depth {
                        return Err(IpcError::RecursionLimitExceeded {
                            depth,
                            max: max_depth,
                        });
                    }
                }
                b'}' | b']' => {
                    depth = depth.saturating_sub(1);
                }
                _ => {}
            }
        }
    }

    Ok(())
}

/// Recursively measure the nesting depth of a `serde_json::Value`.
pub fn check_value_depth(
    val: &serde_json::Value,
    current: usize,
    max: usize,
) -> Result<(), IpcError> {
    if current > max {
        return Err(IpcError::RecursionLimitExceeded {
            depth: current,
            max,
        });
    }

    match val {
        serde_json::Value::Array(arr) => {
            for item in arr {
                check_value_depth(item, current + 1, max)?;
            }
        }
        serde_json::Value::Object(map) => {
            for (_, item) in map {
                check_value_depth(item, current + 1, max)?;
            }
        }
        _ => {}
    }

    Ok(())
}

/// Validate that a method name conforms to allowed character and length rules.
///
/// Rules:
/// - Length between 1 and 64 bytes.
/// - ASCII alphanumeric, periods, underscores, and hyphens only (`[a-zA-Z0-9_.-]`).
/// - Cannot start or end with a period, hyphen, or underscore.
/// - Cannot contain consecutive periods (`..`).
pub fn validate_method_name(method: &str) -> Result<(), IpcError> {
    if method.len() < MIN_METHOD_NAME_LENGTH || method.len() > MAX_METHOD_NAME_LENGTH {
        return Err(IpcError::InvalidMethodName(format!(
            "Length must be between {MIN_METHOD_NAME_LENGTH} and {MAX_METHOD_NAME_LENGTH} characters (was {})",
            method.len()
        )));
    }

    if method.starts_with('.') || method.starts_with('-') || method.starts_with('_') {
        return Err(IpcError::InvalidMethodName(
            "Method name cannot begin with '.', '-', or '_'".to_string(),
        ));
    }

    if method.ends_with('.') || method.ends_with('-') || method.ends_with('_') {
        return Err(IpcError::InvalidMethodName(
            "Method name cannot end with '.', '-', or '_'".to_string(),
        ));
    }

    if method.contains("..") {
        return Err(IpcError::InvalidMethodName(
            "Method name cannot contain consecutive periods '..'".to_string(),
        ));
    }

    for ch in method.chars() {
        if !(ch.is_ascii_alphanumeric() || ch == '.' || ch == '_' || ch == '-') {
            return Err(IpcError::InvalidMethodName(format!(
                "Invalid character '{ch}' in method name. Only ASCII alphanumeric, '.', '_', and '-' are allowed"
            )));
        }
    }

    Ok(())
}

/// Validate that a request ID falls within safe JavaScript integer limits.
pub fn validate_request_id(id: u64) -> Result<(), IpcError> {
    if id > MAX_REQUEST_ID {
        return Err(IpcError::InvalidIdRange {
            id,
            max: MAX_REQUEST_ID,
        });
    }
    Ok(())
}

/// Validate raw message size, empty state, null bytes, and depth limits.
pub fn validate_raw_message(raw: &str) -> Result<(), IpcError> {
    if raw.len() > MAX_MESSAGE_SIZE_BYTES {
        tracing::warn!(
            size = raw.len(),
            max = MAX_MESSAGE_SIZE_BYTES,
            "IPC message exceeds maximum allowed raw size"
        );
        return Err(IpcError::MessageTooLarge {
            size: raw.len(),
            max: MAX_MESSAGE_SIZE_BYTES,
        });
    }

    if raw.is_empty() {
        tracing::warn!("IPC message is empty");
        return Err(IpcError::EmptyMessage);
    }

    if raw.contains('\0') {
        tracing::warn!("IPC message contains null byte");
        return Err(IpcError::NullByteDetected);
    }

    check_nesting_depth(raw, MAX_JSON_DEPTH)?;

    Ok(())
}

/// Parse and validate an incoming raw IPC message string into a typed `Request`.
///
/// Enforces all sizing, formatting, schema, ID range, and method name constraints.
pub fn parse_request(raw: &str) -> Result<Request, IpcError> {
    validate_raw_message(raw)?;

    let request: Request = serde_json::from_str(raw).map_err(|e| {
        tracing::warn!(error = %e, "IPC JSON deserialization rejected");
        IpcError::InvalidJson(e.to_string())
    })?;

    validate_request_id(request.id)?;
    validate_method_name(&request.method)?;
    check_value_depth(&request.params, 1, MAX_JSON_DEPTH)?;

    Ok(request)
}

/// Capability model holding the explicit set of methods a window is authorized to call.
///
/// Default state is strictly EMPTY (default-deny, zero permissions).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Capabilities {
    methods: BTreeSet<String>,
}

impl Capabilities {
    /// Create a new empty capability set (default-deny).
    pub fn new() -> Self {
        Self {
            methods: BTreeSet::new(),
        }
    }

    /// Grant permission to call a specific method name.
    pub fn grant(&mut self, method: impl Into<String>) {
        self.methods.insert(method.into());
    }

    /// Revoke permission to call a specific method name.
    pub fn revoke(&mut self, method: &str) {
        self.methods.remove(method);
    }

    /// Check if permission is granted for a specific method name.
    pub fn is_allowed(&self, method: &str) -> bool {
        self.methods.contains(method)
    }

    /// Return the count of currently granted methods.
    pub fn len(&self) -> usize {
        self.methods.len()
    }

    /// Return true if no methods are granted.
    pub fn is_empty(&self) -> bool {
        self.methods.is_empty()
    }
}

/// Signature for synchronous IPC handler functions.
pub type HandlerFn =
    Arc<dyn Fn(&serde_json::Value) -> Result<serde_json::Value, String> + Send + Sync>;

/// Built-in handler for `core.ping`: returns "pong" and the framework version.
pub fn handle_core_ping(_params: &serde_json::Value) -> Result<serde_json::Value, String> {
    Ok(serde_json::json!({
        "message": "pong",
        "version": FRAMEWORK_VERSION,
    }))
}

/// Built-in handler for `core.echo`: returns its exact parameters.
pub fn handle_core_echo(params: &serde_json::Value) -> Result<serde_json::Value, String> {
    Ok(params.clone())
}

/// Standard known capabilities available in wavical-ipc.
pub const KNOWN_CAPABILITIES: &[&str] = &["core.echo", "core.ping"];

/// Helper function returning the list of valid/known capabilities.
pub fn known_capabilities() -> Vec<String> {
    KNOWN_CAPABILITIES.iter().map(|s| s.to_string()).collect()
}

/// Registry mapping method names to their corresponding handler functions.
#[derive(Default, Clone)]
pub struct HandlerRegistry {
    handlers: std::collections::BTreeMap<String, HandlerFn>,
}

impl HandlerRegistry {
    /// Create an empty handler registry.
    pub fn new() -> Self {
        Self {
            handlers: std::collections::BTreeMap::new(),
        }
    }

    /// Create a registry pre-populated with standard core methods (`core.ping` and `core.echo`).
    pub fn with_core_handlers() -> Self {
        let mut registry = Self::new();
        registry.register("core.ping", handle_core_ping);
        registry.register("core.echo", handle_core_echo);
        registry
    }

    /// Register a method handler.
    pub fn register<F>(&mut self, method: impl Into<String>, handler: F)
    where
        F: Fn(&serde_json::Value) -> Result<serde_json::Value, String> + Send + Sync + 'static,
    {
        self.handlers.insert(method.into(), Arc::new(handler));
    }

    /// Check if a method is registered.
    pub fn has_handler(&self, method: &str) -> bool {
        self.handlers.contains_key(method)
    }

    /// Retrieve a handler reference if registered.
    pub fn get(&self, method: &str) -> Option<&HandlerFn> {
        self.handlers.get(method)
    }

    /// Return all registered method names in sorted alphabetical order.
    pub fn registered_methods(&self) -> Vec<String> {
        self.handlers.keys().cloned().collect()
    }
}

/// Route and dispatch a validated `Request` against a window's `Capabilities` and `HandlerRegistry`.
///
/// CRITICAL SECURITY INVARIANT:
/// Both ungranted methods and unknown methods return the exact same generic error
/// (`GENERIC_METHOD_ERROR`) to the caller, while precise diagnostic details are logged via tracing.
pub fn dispatch(
    request: &Request,
    capabilities: &Capabilities,
    registry: &HandlerRegistry,
) -> Response {
    if !capabilities.is_allowed(&request.method) {
        tracing::warn!(
            id = request.id,
            method = %request.method,
            "IPC capability denied: method is not in the allowed capability set"
        );
        return Response::error(request.id, GENERIC_METHOD_ERROR);
    }

    let Some(handler) = registry.get(&request.method) else {
        tracing::warn!(
            id = request.id,
            method = %request.method,
            "IPC unknown method: method is granted by capability but not registered in handler registry"
        );
        return Response::error(request.id, GENERIC_METHOD_ERROR);
    };

    match handler(&request.params) {
        Ok(result) => {
            tracing::debug!(
                id = request.id,
                method = %request.method,
                "IPC handler invocation succeeded"
            );
            Response::success(request.id, result)
        }
        Err(err) => {
            tracing::error!(
                id = request.id,
                method = %request.method,
                error = %err,
                "IPC handler execution failed"
            );
            // INFORMATION LEAKAGE DEFENSE (WP7/WP8):
            // If the handler error contains filesystem paths or internal symbols, sanitize it.
            let safe_err = if err.contains('/') || err.contains('\\') || err.contains(':') {
                GENERIC_HANDLER_ERROR.to_string()
            } else {
                err
            };
            Response::error(request.id, safe_err)
        }
    }
}

/// Complete end-to-end processing pipeline: validates, parses, checks capabilities, and dispatches.
pub fn dispatch_raw(
    raw: &str,
    capabilities: &Capabilities,
    registry: &HandlerRegistry,
) -> Result<Response, IpcError> {
    let request = parse_request(raw)?;
    Ok(dispatch(&request, capabilities, registry))
}

